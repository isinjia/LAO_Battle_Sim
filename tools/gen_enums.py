"""Generate engine/enums.js from the client's C# enums (LoTable.cs, GlobalDefines.cs, battle scripts)."""
import re, os, json, glob, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import project_path
ROOT = os.path.join(project_path.resolve(sys.argv[1] if len(sys.argv) > 1 else None), 'Assets', '_Scripts')
OUT = os.path.join(os.path.dirname(__file__), '..', 'engine', 'enums.js')

enums = {}
files = glob.glob(os.path.join(ROOT, '**', '*.cs'), recursive=True)
pat = re.compile(r'\benum\s+(\w+)\s*(?::\s*\w+)?\s*\{(.*?)\}', re.S)
for f in files:
    if os.sep + 'Editor' + os.sep in f: continue
    src = open(f, encoding='utf-8-sig', errors='replace').read()
    src = re.sub(r'//[^\n]*', '', src)
    src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
    src = re.sub(r'^\s*#.*$', '', src, flags=re.M)
    for name, body in pat.findall(src):
        vals, cur = {}, -1
        ok = True
        for part in body.split(','):
            part = part.strip()
            if not part: continue
            part = re.sub(r'\[[^\]]*\]', '', part).strip()
            if '=' in part:
                k, v = [x.strip() for x in part.split('=', 1)]
                try: cur = int(v, 0)
                except ValueError:
                    if v in vals: cur = vals[v]
                    else: ok = False; break
            else:
                k = part; cur += 1
            if not re.match(r'^\w+$', k): ok = False; break
            vals[k] = cur
        if ok and vals and name not in enums:
            enums[name] = vals

with open(OUT, 'w', encoding='utf-8') as fo:
    fo.write('// Generated by tools/gen_enums.py from Assets/_Scripts C# enums. Do not edit.\n')
    fo.write('(function(){ const E = ' + json.dumps(enums, ensure_ascii=False, separators=(',', ':')) + ';\n')
    fo.write('const R = {}; for (const n in E) { R[n] = {}; for (const k in E[n]) R[n][E[n][k]] = k; }\n')
    fo.write('(window.LOSim = window.LOSim || {}).E = E; window.LOSim.Ename = R; })();\n')
print(len(enums), 'enums ->', OUT)
for k in ('BUFFEFFECT_TYPE', 'BUFFEFFECT_TRIGGER_TYPE', 'ACTOR_ATTR_TYPE', 'VALUE_TYPE', 'TARGET_TYPE', 'BUFFEFFECT_ERASE_TYPE'):
    print(k, len(enums.get(k, {})))
